from dotenv import load_dotenv
from langchain.agents import create_agent
from langchain.agents.middleware import (
    AgentMiddleware,
    ModelCallLimitMiddleware,
    ToolCallLimitMiddleware,
)
from langchain.tools import tool
from langchain_core.messages import HumanMessage
from pychomsky.chchat import GCPVertexAnthropicChatWrapper
from langchain_tavily import TavilySearch
from pydantic import BaseModel, Field
from typing import Any, List

load_dotenv()


class Source(BaseModel):
    """Schema for a source used by the agent"""

    url: str = Field(description="The url of the source")


class AgentResponse(BaseModel):
    """Schema for the response generated by the agent with content and sources"""

    answerContent: str = Field(description="The answer content")
    sources: List[Source] = Field(
        default_factory=list, description="The sources used to answer the question"
    )


tavily_search = TavilySearch(max_results=5)

llm = GCPVertexAnthropicChatWrapper(
    chgw_endpoint="https://chomskygw.vip.qa.ebay.com/api/v1/genai",
    model_name=("gcp-chat-completions-anthropic-claude-sonnet-4.6-sandbox"),
    temperature=0,
    max_output_tokens=1000,
    debug=True,
)
toolList = [tavily_search]

agent = create_agent(
    model=llm,
    tools=toolList,
    response_format=AgentResponse
)


def main() -> None:
    print("Hello from langchain-course!")
    # hMessage = HumanMessage(content=""" search for 3 job postings for an ai engineer
    #                                                    using langchain in the bay area on linkedin and
    #                                                    list their details""")
    hMessage = HumanMessage(content=""" what is weather in chennai?""")
    response = agent.invoke({"messages": [hMessage]})
    print_response(response)


def print_response(response: dict[str, Any]) -> None:
    for m in response["messages"]:
        m.pretty_print()
        print("\n")


if __name__ == "__main__":
    main()
